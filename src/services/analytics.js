/**
 * analytics.js — отправка событий в Google Analytics 4.
 *
 * Три правила, из которых всё вытекает:
 *
 * 1. **Молчим без согласия.** `gtag` появляется в окне только после того, как
 *    человек нажал «Принять» в плашке (см. loadGA в App.jsx). Пока его нет —
 *    события просто не отправляются, никакой очереди «на потом».
 * 2. **Никаких личных данных.** Отправляем только идентификаторы контента
 *    (id узла, курса, шаблона) и служебные признаки. Ни адресов, ни имён, ни
 *    текста, который человек ввёл сам (поисковые запросы — тоже текст
 *    пользователя, поэтому уходит только факт «нашлось / не нашлось»).
 * 3. **Имена событий и параметров — стабильные.** По ним в GA настроены
 *    пользовательские параметры; переименование обнулит отчёты.
 *
 * Что именно отслеживаем — docs/analytics-events.md.
 */

/** Отправить событие. Тихо ничего не делает, если аналитика не загружена. */
export function track(event, params = {}) {
  try {
    if (typeof window === 'undefined') return;
    const gtag = window.gtag;
    // __ga_loaded ставится только после согласия; без него gtag — заглушка
    // consent-mode, и слать в неё события бессмысленно.
    if (!gtag || !window.__ga_loaded) return;

    const clean = {};
    for (const [k, v] of Object.entries(params)) {
      if (v === undefined || v === null || v === '') continue;
      // Обрезаем на всякий случай: GA4 режет значения на 100 символах.
      clean[k] = typeof v === 'string' ? v.slice(0, 100) : v;
    }
    gtag('event', event, clean);
  } catch { /* аналитика не должна ломать приложение */ }
}

/**
 * Просмотр «страницы» внутри приложения. У нас одностраничное приложение с
 * настоящими адресами (/ru/node/cap-search), и без явного вызова GA считает
 * весь визит одной страницей.
 */
export function trackPageView(path, title) {
  track('page_view', { page_path: path, page_title: title });
}
